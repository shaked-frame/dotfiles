-- Run: env -u REX_SERVER -u REX_SESSION -u REX_BLOCK -u HERDR_ENV nvim --headless -n -i NONE -c "lua dofile('scripts/gen-themes.lua')"
--
-- Writes the Solarized Osaka theme for every tool outside Neovim, from the
-- solarized-osaka.nvim palette with the configured style (vivid) and its own
-- extras exporters, so the terminal, git diffs and pickers match the editor:
--
--   ghostty/themes/solarized-osaka-vivid  Ghostty; Rex imports the same file
--   delta/solarized-osaka.gitconfig       delta diff colors (included from ~/.gitconfig)
--   bat/themes/solarized-osaka.tmTheme    syntax colors for bat and delta
--   fzf/fzfrc                             fzf colors ($FZF_DEFAULT_OPTS_FILE in ~/.zshrc)
--   yazi/theme.toml                       yazi
--   lazygit/config.yml gui.theme          by hand: copy from the lazygit extra
--
-- Background and text color are what Neovim draws: Normal is transparent, so
-- the terminal background shows behind windows, and floats (the Snacks picker)
-- paint NormalFloat's. Making the terminal use NormalFloat's color makes the
-- two the same. Rerun after changing the colorscheme's `style` or upgrading
-- the plugin, then `chezmoi apply` (rebuilds bat's cache) and re-import the
-- Ghostty file in Rex.

vim.wait(5000, function() return Config.later_pending == 0 end)

local hex = function(n) return string.format('#%06x', n) end
local normal = vim.api.nvim_get_hl(0, { name = 'Normal', link = false })
local float = vim.api.nvim_get_hl(0, { name = 'NormalFloat', link = false })
local colors = require('solarized-osaka.colors').setup()
colors.bg = hex(float.bg)
colors.fg = hex(normal.fg)

local root = 'home/dot_config/'
local stamp = 'Generated by scripts/gen-themes.lua from solarized-osaka.nvim (vivid); edit that, not this file.'
local extra = function(name, ...) return require('solarized-osaka.extra.' .. name).generate(...) end

local function write(path, comment, body)
  vim.fn.mkdir(vim.fs.dirname(root .. path), 'p')
  local file = assert(io.open(root .. path, 'w'))
  file:write(comment and (comment .. ' ' .. stamp .. '\n\n') or '', body)
  file:close()
  print('wrote ' .. root .. path)
end

write('ghostty/themes/solarized-osaka-vivid', '#', extra('ghostty', colors))

write(
  'delta/solarized-osaka.gitconfig',
  '#',
  extra('delta', colors) .. '  syntax-theme                  = solarized-osaka\n'
)

-- tmTheme is XML: no leading comment before the declaration.
write('bat/themes/solarized-osaka.tmTheme', nil, extra('sublime', colors))

-- The exporter predates yazi 25: [manager] is now [mgr], and filetype rules
-- match paths with `url` (yazi refuses to load a rule keyed `name`).
local yazi = extra('yazi', colors):gsub('%[manager%]', '[mgr]'):gsub('{ name = ', '{ url = ')
write('yazi/theme.toml', '#', yazi)

-- Colors only: the exporter also sets layout and border options, which are
-- not a theme's business.
local fzf = {}
for line in extra('fzf'):gmatch('[^\n]+') do
  local opt = line:match('^%s*(%-%-color=%S+)')
  if opt then table.insert(fzf, opt) end
end
write('fzf/fzfrc', '#', table.concat(fzf, '\n') .. '\n')

io.stdout:write('\n-- lazygit gui.theme --\n', extra('lazygit', colors), '\n')
vim.cmd('qa!')
